const DAY_MS = 86_400_000;

// ─────────────────────────────────────────────────────────────────────────────
// CRON — auto-generate cycles
// ─────────────────────────────────────────────────────────────────────────────

export async function runRetainedCycleGeneration({
  trigger = "CRON",
  actorId = null,
} = {}) {
  const lookaheadDays = await getSettingInt("retained.cron.lookaheadDays", 3);
  const now = new Date();
  const horizon = new Date(now.getTime() + lookaheadDays * DAY_MS);

  const due = await prisma.retainedStaffMember.findMany({
    where: {
      status: "ACTIVE",
      payFrequency: { not: "ON_DEMAND" },
      nextCycleAt: { not: null, lte: horizon },
    },
    orderBy: { nextCycleAt: "asc" },
  });

  const results = [];

  for (const member of due) {
    try {
      const result = await generateCycleForMember(member, { trigger, actorId });
      if (result) results.push(result);
    } catch (err) {
      console.error(`[retainedCron] member ${member.id} failed:`, err.message);
      results.push({ memberId: member.id, error: err.message });
    }
  }

  return {
    processed: due.length,
    created: results.filter((r) => r.cycleId).length,
    results,
  };
}

async function generateCycleForMember(member, { trigger, actorId }) {
  const payDate = member.nextCycleAt;
  const periodStart = new Date(payDate);
  periodStart.setHours(0, 0, 0, 0);
  const periodEnd = endOfPeriod(member.payFrequency, periodStart);

  const dateKey = periodStart.toISOString().slice(0, 10);
  const cronLockKey = `${member.id}:${dateKey}`;

  // Idempotency
  const exists = await prisma.retainedPayrollCycle.findUnique({
    where: { cronLockKey },
  });
  if (exists) return null;

  const amounts = computeCycleAmounts(member);

  const cycle = await prisma.retainedPayrollCycle.create({
    data: {
      memberId: member.id,
      hirerId: member.hirerId,
      workerId: member.workerId,
      type: "REGULAR",
      periodStart,
      periodEnd,
      payDate,
      label: labelFor(member, periodStart, periodEnd),
      ...amounts,
      currency: member.currency,
      status: "AWAITING_PAYMENT",
      autoGenerated: true,
      cronLockKey,
    },
  });

  // Advance member's nextCycleAt
  const next = nextCycleDate(member.payFrequency, payDate);
  await prisma.retainedStaffMember.update({
    where: { id: member.id },
    data: {
      nextCycleAt: next,
      cyclesCount: { increment: 1 },
      currencyLocked: true,
    },
  });

  await logAdminAction({
    req: null,
    adminId: actorId ?? member.hirerId,
    action: "RETAINED_CYCLE_CRON_GENERATED",
    targetType: "RETAINED_STAFF_CYCLE",
    targetId: cycle.id,
    description: `Auto-generated ${member.payFrequency} payroll cycle for ${member.jobTitle}`,
    after: { netAmount: cycle.netAmount, currency: cycle.currency, payDate },
    meta: { trigger },
  });

  try {
    await createNotification({
      userId: member.hirerId,
      title: "Payroll cycle ready 💰",
      body: `A new payroll cycle is ready to fund for ${member.jobTitle} (${formatMoney(cycle.netAmount, cycle.currency)}).`,
      type: "RETAINED_CYCLE_SCHEDULED",
      icon: "FaMoneyCheckAlt",
      data: { cycleId: cycle.id, memberId: member.id },
    });
  } catch {}

  return { memberId: member.id, cycleId: cycle.id };
}

function labelFor(member, start, end) {
  const s = start.toISOString().slice(0, 10);
  const e = end.toISOString().slice(0, 10);
  return `${member.jobTitle} — ${s} → ${e}`;
}

// ─────────────────────────────────────────────────────────────────────────────
// MANUAL CYCLE
// ─────────────────────────────────────────────────────────────────────────────

export async function createManualCycle(memberId, hirerId, payload, ctx = {}) {
  const member = await prisma.retainedStaffMember.findFirst({
    where: { id: memberId, hirerId },
  });
  if (!member) throw httpError(404, "Retained staff member not found");
  if (member.status === "ENDED" || member.status === "TERMINATED")
    throw httpError(400, "Cannot create a cycle for an ended membership");

  const {
    type = "MANUAL",
    periodStart = new Date(),
    periodEnd = new Date(),
    payDate = new Date(),
    baseAmount = member.payRate,
    bonusAmount = 0,
    deductionAmount = 0,
    label = null,
    notes = null,
    paymentMethod = "ESCROW",
  } = payload;

  const amounts = computeCycleAmounts(member, {
    baseAmount,
    bonusAmount,
    deductionAmount,
  });

  const cycle = await prisma.retainedPayrollCycle.create({
    data: {
      memberId,
      hirerId,
      workerId: member.workerId,
      type,
      periodStart: new Date(periodStart),
      periodEnd: new Date(periodEnd),
      payDate: new Date(payDate),
      label:
        label ??
        `${type} — ${new Date(periodStart).toISOString().slice(0, 10)}`,
      ...amounts,
      currency: member.currency,
      status: "AWAITING_PAYMENT",
      paymentMethod,
      autoGenerated: false,
    },
  });

  await prisma.retainedStaffMember.update({
    where: { id: memberId },
    data: {
      cyclesCount: { increment: 1 },
      currencyLocked: true,
    },
  });

  await logAdminAction({
    req: ctx.req,
    adminId: hirerId,
    action: "RETAINED_CYCLE_CREATED",
    targetType: "RETAINED_STAFF_CYCLE",
    targetId: cycle.id,
    description: `Created ${type} cycle for ${member.jobTitle}`,
    after: { netAmount: cycle.netAmount, currency: cycle.currency, type },
  });

  return cycle;
}

// ─────────────────────────────────────────────────────────────────────────────
// PAY CYCLE  — creates Booking (financial shell)
// ─────────────────────────────────────────────────────────────────────────────

export async function payCycle(cycleId, hirerId, opts = {}, ctx = {}) {
  const cycle = await prisma.retainedPayrollCycle.findFirst({
    where: { id: cycleId, hirerId },
    include: { member: true },
  });
  if (!cycle) throw httpError(404, "Payroll cycle not found");
  if (cycle.status !== "AWAITING_PAYMENT")
    throw httpError(400, `Cycle is not payable (status: ${cycle.status})`);

  // ✅ If Booking already exists, just return it so the frontend can proceed
  if (cycle.bookingId) {
    const existingBooking = await prisma.booking.findUnique({
      where: { id: cycle.bookingId },
    });
    return { booking: existingBooking, cycleId: cycle.id };
  }

  const paymentMethod = opts.paymentMethod ?? cycle.paymentMethod ?? "ESCROW";

  // Find the worker's primary category (required FK on Booking)
  let category = await prisma.workerCategory.findFirst({
    where: { workerProfile: { userId: cycle.workerId } },
    orderBy: { isPrimary: "desc" },
    include: { category: true },
  });

  if (!category) {
    const anyCategory = await prisma.category.findFirst();
    if (!anyCategory)
      throw httpError(500, "No categories exist in the system.");
    category = { categoryId: anyCategory.id, category: anyCategory };
  }

  const title =
    cycle.label ??
    `${cycle.member.jobTitle} — ${cycle.periodStart.toISOString().slice(0, 10)}`;
  const description =
    cycle.member.description ||
    `Retained staff payroll for ${cycle.member.jobTitle}`;

  // ── Create Booking (financial shell) inside a transaction
  const booking = await prisma.$transaction(async (tx) => {
    const b = await tx.booking.create({
      data: {
        hirerId,
        workerId: cycle.workerId,
        categoryId: category.categoryId,
        title,
        description,
        address: cycle.member.location ?? null,
        scheduledAt: cycle.periodStart,
        estimatedHours: null,
        agreedRate: cycle.workerPayout,
        currency: cycle.currency,
        status: "ACCEPTED",
        notes: cycle.notes ?? null,
        quantity: 1,
        source: "RETAINED_STAFF",
        jobPostId: null,
        snapshotCategoryName: category.category.name,
        snapshotCategoryIcon: category.category.icon,

        // ✅ Location + schedule + HR snapshot
        location: cycle.member.location ?? null,
        latitude: cycle.member.latitude ?? null,
        longitude: cycle.member.longitude ?? null,
        locationType: cycle.member.locationType ?? "ON_SITE",
        workDays: cycle.member.workDays ?? [],
        workStart: cycle.member.workStart ?? null,
        workEnd: cycle.member.workEnd ?? null,
        timezone: cycle.member.timezone ?? null,
        employeeNumber: cycle.member.employeeNumber ?? null,
        managerName: cycle.member.managerName ?? null,
        emergencyContact: cycle.member.emergencyContact ?? null,

        // ✅ NEW: Role metadata snapshot
        employmentType: cycle.member.employmentType ?? null,
        department: cycle.member.department ?? null,
      },
    });

    await tx.retainedPayrollCycle.update({
      where: { id: cycle.id },
      data: {
        bookingId: b.id,
        paymentMethod,
        paidAt: null,
      },
    });

    return b;
  });

  await logAdminAction({
    req: ctx.req,
    adminId: hirerId,
    action: "RETAINED_CYCLE_PAYMENT_MADE",
    targetType: "RETAINED_STAFF_CYCLE",
    targetId: cycle.id,
    description: `Created payment booking for retained cycle`,
    after: { bookingId: booking.id, netAmount: cycle.netAmount },
  });

  return { booking, cycleId: cycle.id };
}

// ─────────────────────────────────────────────────────────────────────────────
// RELEASE FUNDS — delegates to existing staged release
// ─────────────────────────────────────────────────────────────────────────────

export async function releaseCycleFunds(
  cycleId,
  hirerId,
  amount,
  note = null,
  ctx = {},
) {
  const cycle = await prisma.retainedPayrollCycle.findFirst({
    where: { id: cycleId, hirerId },
    include: { member: true },
  });
  if (!cycle) throw httpError(404, "Payroll cycle not found");
  if (!cycle.bookingId)
    throw httpError(400, "Cycle has no payment yet — pay it first");
  if (!["HELD", "PARTIALLY_RELEASED"].includes(cycle.status))
    throw httpError(400, `Cannot release a cycle in status ${cycle.status}`);
  if (typeof amount !== "number" || amount <= 0)
    throw httpError(400, "amount must be > 0");

  const payment = await prisma.payment.findFirst({
    where: { bookingId: cycle.bookingId, status: "HELD" },
  });
  if (!payment) throw httpError(404, "No HELD payment found for this cycle");

  const remaining = payment.workerPayout - payment.releasedAmount;
  if (amount > remaining + 0.01)
    throw httpError(400, `Amount exceeds remaining payout (${remaining})`);

  // ── Delegate to existing release handler
  const release = await releaseEscrowPartial(payment.id, amount, {
    triggeredBy: hirerId,
    triggeredByRole: "HIRER",
    note,
  });

  const updatedPayment = await prisma.payment.findUnique({
    where: { id: payment.id },
  });
  const fullyReleased =
    updatedPayment.releasedAmount >= updatedPayment.workerPayout - 0.01;

  const cycleStatus = fullyReleased ? "RELEASED" : "PARTIALLY_RELEASED";
  await prisma.retainedPayrollCycle.update({
    where: { id: cycle.id },
    data: {
      status: cycleStatus,
      releasedAt: fullyReleased ? new Date() : null,
    },
  });

  if (fullyReleased) {
    // ✅ FIX: Mark the booking as COMPLETED (not PAID)
    await prisma.booking.update({
      where: { id: cycle.bookingId },
      data: { status: "COMPLETED", completedAt: new Date() },
    });

    await prisma.retainedStaffMember.update({
      where: { id: cycle.memberId },
      data: {
        totalPaidLifetime: { increment: cycle.netAmount },
        totalHeld: { decrement: cycle.netAmount },
        lastPaidAt: new Date(),
      },
    });
  }

  await logAdminAction({
    req: ctx.req,
    adminId: hirerId,
    action: "RETAINED_CYCLE_RELEASED",
    targetType: "RETAINED_STAFF_CYCLE",
    targetId: cycle.id,
    description: fullyReleased
      ? `Fully released cycle (${amount} ${cycle.currency})`
      : `Partially released cycle (${amount} ${cycle.currency})`,
    after: {
      amount,
      remainingAfter:
        updatedPayment.workerPayout - updatedPayment.releasedAmount,
      status: cycleStatus,
    },
  });

  try {
    await createNotification({
      userId: cycle.workerId,
      title: fullyReleased ? "Payroll released ✅" : "Partial release received",
      body: fullyReleased
        ? `Full payroll of ${formatMoney(cycle.netAmount, cycle.currency)} has been released to your wallet.`
        : `${formatMoney(amount, cycle.currency)} has been released to your wallet.`,
      type: fullyReleased
        ? "RETAINED_CYCLE_RELEASED"
        : "RETAINED_CYCLE_PARTIALLY_RELEASED",
      icon: "FaWallet",
      data: { cycleId: cycle.id },
    });
  } catch {}

  return {
    release,
    payment: updatedPayment,
    cycle: { id: cycle.id, status: cycleStatus, fullyReleased },
  };
}

// ─────────────────────────────────────────────────────────────────────────────
// CANCEL
// ─────────────────────────────────────────────────────────────────────────────

export async function cancelCycle(cycleId, hirerId, reason = null, ctx = {}) {
  const cycle = await prisma.retainedPayrollCycle.findFirst({
    where: { id: cycleId, hirerId },
  });
  if (!cycle) throw httpError(404, "Payroll cycle not found");
  if (!["AWAITING_PAYMENT", "SCHEDULED"].includes(cycle.status))
    throw httpError(400, `Cannot cancel cycle in status ${cycle.status}`);

  await prisma.retainedPayrollCycle.update({
    where: { id: cycle.id },
    data: {
      status: "CANCELLED",
      cancelledAt: new Date(),
      failureReason: reason ?? null,
    },
  });

  await logAdminAction({
    req: ctx.req,
    adminId: hirerId,
    action: "RETAINED_CYCLE_CANCELLED",
    targetType: "RETAINED_STAFF_CYCLE",
    targetId: cycle.id,
    description: `Cancelled unpaid cycle${reason ? `: ${reason}` : ""}`,
    before: { status: cycle.status },
    after: { status: "CANCELLED" },
  });

  return { cancelled: true };
}

// ─────────────────────────────────────────────────────────────────────────────
// Utilities
// ─────────────────────────────────────────────────────────────────────────────

function httpError(status, message) {
  const err = new Error(message);
  err.statusCode = status;
  return err;
}

function formatMoney(amount, currency) {
  return `${currency} ${Number(amount).toLocaleString(undefined, {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}`;
}

async function getSettingInt(key, fallback) {
  try {
    const row = await prisma.appSettings.findUnique({ where: { key } });
    if (!row) return fallback;
    const n = parseInt(row.value, 10);
    return Number.isFinite(n) ? n : fallback;
  } catch {
    return fallback;
  }
}

export async function deleteCycle(cycleId, hirerId, ctx = {}) {
  const cycle = await prisma.retainedPayrollCycle.findFirst({
    where: { id: cycleId, hirerId },
  });

  if (!cycle) throw httpError(404, "Payroll cycle not found");

  // Only allow deleting cycles that haven't been paid yet
  if (cycle.status !== "AWAITING_PAYMENT" && cycle.status !== "CANCELLED") {
    throw httpError(
      409,
      "Cannot delete a cycle that is already paid or in progress. Cancel it instead.",
    );
  }

  await prisma.retainedPayrollCycle.delete({
    where: { id: cycleId },
  });

  // Update the member's cycle count
  await prisma.retainedStaffMember.update({
    where: { id: cycle.memberId },
    data: { cyclesCount: { decrement: 1 } },
  });

  await logAdminAction({
    req: ctx.req,
    adminId: hirerId,
    action: "RETAINED_CYCLE_CANCELLED", // Reusing the cancel action for audit
    targetType: "RETAINED_STAFF_CYCLE",
    targetId: cycleId,
    description: `Deleted an unpaid payroll cycle`,
    before: { status: cycle.status, amount: cycle.netAmount },
  });

  return { deleted: true };
}
