// scripts/seed-retained-staff-test-data.js
// ─────────────────────────────────────────────────────────────────────────────
// Seeds realistic Retained Staff test data.
// Run: node scripts/seed-retained-staff-test-data.js
// Safe to re-run — skips existing memberships by (hirer, worker, ACTIVE).
// ─────────────────────────────────────────────────────────────────────────────

import prisma from "../src/config/database.js";
import crypto from "crypto";
import {
  computeCycleAmounts,
  nextCycleDate,
} from "../src/services/retainedStaff.service.js";

const uuid = () => crypto.randomUUID();
const daysAgo = (n) => new Date(Date.now() - n * 86_400_000);
const daysFromNow = (n) => new Date(Date.now() + n * 86_400_000);

async function findUsers() {
  const workers = await prisma.user.findMany({
    where: { role: "WORKER", isActive: true, isBanned: false },
    take: 3,
    select: { id: true, firstName: true, lastName: true, email: true },
  });
  const hirers = await prisma.user.findMany({
    where: { role: "HIRER", isActive: true, isBanned: false },
    take: 2,
    select: { id: true, firstName: true, lastName: true, email: true },
  });
  if (workers.length < 1 || hirers.length < 1) {
    throw new Error(
      `Need at least 1 active WORKER and 1 active HIRER. ` +
        `Found ${workers.length} workers, ${hirers.length} hirers.`,
    );
  }
  return { workers, hirers };
}

async function ensureMembership(hirerId, worker, cfg) {
  const existing = await prisma.retainedStaffMember.findFirst({
    where: { hirerId, workerId: worker.id, status: "ACTIVE" },
  });
  if (existing) {
    console.log(`  ⏭  Exists: ${worker.firstName} → ${cfg.jobTitle}`);
    return existing;
  }

  const m = await prisma.retainedStaffMember.create({
    data: {
      hirerId,
      workerId: worker.id,
      jobTitle: cfg.jobTitle,
      department: cfg.department,
      employmentType: cfg.employmentType || "FULL_TIME",
      description: cfg.description,
      payRate: cfg.payRate,
      currency: cfg.currency || "NGN",
      payFrequency: cfg.payFrequency,
      workDays: ["MON", "TUE", "WED", "THU", "FRI"],
      workStart: "09:00",
      workEnd: "17:00",
      timezone: "Africa/Lagos",
      employeeNumber: cfg.employeeNumber,
      managerName: cfg.managerName,
      startedAt: daysAgo(180),
      nextCycleAt: nextCycleDate(cfg.payFrequency, new Date()),
    },
  });

  // Permanent conversation (best-effort)
  try {
    await prisma.conversation.create({
      data: {
        retainedMemberId: m.id,
        users: { create: [{ userId: hirerId }, { userId: worker.id }] },
      },
    });
  } catch (err) {
    console.warn(`  ⚠ Conversation create failed: ${err.message}`);
  }

  console.log(
    `  ✅ Created: ${worker.firstName} ${worker.lastName} as ${cfg.jobTitle} ` +
      `(${cfg.currency || "NGN"} ${cfg.payRate}/${cfg.payFrequency})`,
  );
  return m;
}

async function createCycle(member, cfg) {
  const existing = await prisma.retainedPayrollCycle.findFirst({
    where: {
      memberId: member.id,
      periodStart: cfg.periodStart,
      periodEnd: cfg.periodEnd,
    },
  });
  if (existing) {
    console.log(`  ⏭  Cycle exists: ${cfg.label}`);
    return existing;
  }

  const amounts = computeCycleAmounts(member, {
    baseAmount: cfg.baseAmount ?? member.payRate,
    bonusAmount: cfg.bonusAmount ?? 0,
    deductionAmount: cfg.deductionAmount ?? 0,
  });

  const cycle = await prisma.retainedPayrollCycle.create({
    data: {
      memberId: member.id,
      hirerId: member.hirerId,
      workerId: member.workerId,
      type: cfg.type || "REGULAR",
      periodStart: cfg.periodStart,
      periodEnd: cfg.periodEnd,
      payDate: cfg.payDate,
      label: cfg.label,
      ...amounts,
      currency: member.currency,
      status: cfg.status,
      autoGenerated: cfg.autoGenerated ?? false,
      paidAt: cfg.paidAt ?? null,
      releasedAt: cfg.releasedAt ?? null,
      cancelledAt: cfg.cancelledAt ?? null,
    },
  });
  console.log(`  ✅ Cycle: ${cfg.label} [${cfg.status}]`);
  return cycle;
}

async function run() {
  console.log("\n🌱 Seeding Retained Staff test data...\n");

  const { workers, hirers } = await findUsers();
  console.log(`👥 Found ${workers.length} workers, ${hirers.length} hirers\n`);

  const h1 = hirers[0];
  const h2 = hirers[1] || hirers[0];
  const w1 = workers[0];
  const w2 = workers[1] || workers[0];
  const w3 = workers[2] || workers[0];

  console.log("═══ Memberships ═══");
  const m1 = await ensureMembership(h1.id, w1, {
    jobTitle: "Full-Stack Developer",
    department: "Engineering",
    description: "Senior developer building the SkilledProz web platform.",
    payRate: 350000,
    currency: "NGN",
    payFrequency: "MONTHLY",
    employeeNumber: "EMP-001",
    managerName: `${h1.firstName} ${h1.lastName}`,
  });

  const m2 = await ensureMembership(h1.id, w2, {
    jobTitle: "Content Writer",
    department: "Marketing",
    description: "Blog posts, product copy, and social media content.",
    payRate: 80000,
    currency: "NGN",
    payFrequency: "WEEKLY",
    employeeNumber: "EMP-002",
    managerName: `${h1.firstName} ${h1.lastName}`,
  });

  const m3 = await ensureMembership(h2.id, w3, {
    jobTitle: "Customer Support Specialist",
    department: "Operations",
    description: "Handles inbound support tickets and live chat.",
    payRate: 180000,
    currency: "NGN",
    payFrequency: "MONTHLY",
    employeeNumber: "EMP-003",
    managerName: `${h2.firstName} ${h2.lastName}`,
  });

  console.log("\n═══ Payroll Cycles ═══");
  const now = new Date();
  const monthStart = (o) => new Date(now.getFullYear(), now.getMonth() + o, 1);
  const monthEnd = (o) =>
    new Date(now.getFullYear(), now.getMonth() + o + 1, 0);

  // m1: 2 RELEASED, 1 PARTIALLY_RELEASED, 1 AWAITING_PAYMENT
  await createCycle(m1, {
    label: "2 months ago Salary",
    periodStart: monthStart(-2),
    periodEnd: monthEnd(-2),
    payDate: monthStart(-1),
    status: "RELEASED",
    paidAt: monthStart(-1),
    releasedAt: monthStart(-1),
  });
  await createCycle(m1, {
    label: "Last month Salary",
    periodStart: monthStart(-1),
    periodEnd: monthEnd(-1),
    payDate: monthStart(0),
    status: "PARTIALLY_RELEASED",
    paidAt: monthStart(0),
  });
  await createCycle(m1, {
    label: "Current month Salary",
    periodStart: monthStart(0),
    periodEnd: monthEnd(0),
    payDate: monthStart(1),
    status: "AWAITING_PAYMENT",
  });

  // m2: 2 RELEASED weekly + 1 awaiting
  await createCycle(m2, {
    label: "Week 1",
    periodStart: daysAgo(21),
    periodEnd: daysAgo(15),
    payDate: daysAgo(14),
    status: "RELEASED",
    paidAt: daysAgo(14),
    releasedAt: daysAgo(14),
  });
  await createCycle(m2, {
    label: "Week 2",
    periodStart: daysAgo(14),
    periodEnd: daysAgo(8),
    payDate: daysAgo(7),
    status: "RELEASED",
    paidAt: daysAgo(7),
    releasedAt: daysAgo(7),
  });
  await createCycle(m2, {
    label: "Week 3 (current)",
    periodStart: daysAgo(7),
    periodEnd: daysFromNow(0),
    payDate: daysFromNow(1),
    status: "AWAITING_PAYMENT",
  });

  // m3: 1 cancelled, 1 awaiting
  await createCycle(m3, {
    label: "Cancelled duplicate",
    periodStart: monthStart(-1),
    periodEnd: monthEnd(-1),
    payDate: monthStart(0),
    status: "CANCELLED",
    cancelledAt: daysAgo(5),
  });
  await createCycle(m3, {
    label: "Current month",
    periodStart: monthStart(0),
    periodEnd: monthEnd(0),
    payDate: monthStart(1),
    status: "AWAITING_PAYMENT",
  });

  console.log("\n═══ HR Documents ═══");
  const docCount = await prisma.retainedStaffDocument.count({
    where: { memberId: m1.id },
  });
  if (docCount === 0) {
    await prisma.retainedStaffDocument.createMany({
      data: [
        {
          id: uuid(),
          memberId: m1.id,
          type: "CONTRACT",
          title: "Employment Contract — Full Stack Developer",
          fileUrl: "https://example.com/docs/contract-emp001.pdf",
          mimeType: "application/pdf",
          sizeBytes: 240_000,
          status: "SIGNED",
          uploadedById: h1.id,
          signedAt: daysAgo(180),
        },
        {
          id: uuid(),
          memberId: m1.id,
          type: "NDA",
          title: "Mutual NDA",
          fileUrl: "https://example.com/docs/nda-emp001.pdf",
          mimeType: "application/pdf",
          sizeBytes: 80_000,
          status: "SIGNED",
          uploadedById: h1.id,
          signedAt: daysAgo(180),
        },
      ],
    });
    console.log("  ✅ 2 documents created (CONTRACT, NDA)");
  } else {
    console.log(`  ⏭  ${docCount} documents already exist`);
  }

  console.log("\n═══ HR Notes ═══");
  const noteCount = await prisma.retainedStaffNote.count({
    where: { memberId: m1.id },
  });
  if (noteCount === 0) {
    await prisma.retainedStaffNote.createMany({
      data: [
        {
          id: uuid(),
          memberId: m1.id,
          authorId: h1.id,
          title: "Excellent Q1 performance",
          body: "Shipped 3 major features ahead of schedule. Recommend a bonus for Q2.",
          category: "PRAISE",
          isPrivate: true,
        },
        {
          id: uuid(),
          memberId: m1.id,
          authorId: h1.id,
          title: "Team meeting note",
          body: "Discussed switching from weekly to monthly cadence.",
          category: "GENERAL",
          isPrivate: true,
        },
      ],
    });
    console.log("  ✅ 2 HR notes created");
  } else {
    console.log(`  ⏭  ${noteCount} notes already exist`);
  }

  console.log("\n═══ Recomputing rollups ═══");
  for (const m of [m1, m2, m3]) {
    const cycles = await prisma.retainedPayrollCycle.findMany({
      where: { memberId: m.id },
      select: { status: true, netAmount: true, releasedAt: true },
    });
    let totalPaidLifetime = 0;
    let totalHeld = 0;
    let lastPaidAt = null;
    for (const c of cycles) {
      if (c.status === "RELEASED") {
        totalPaidLifetime += c.netAmount;
        if (c.releasedAt && (!lastPaidAt || c.releasedAt > lastPaidAt)) {
          lastPaidAt = c.releasedAt;
        }
      } else if (c.status === "HELD" || c.status === "PARTIALLY_RELEASED") {
        totalHeld += c.netAmount;
      }
    }
    await prisma.retainedStaffMember.update({
      where: { id: m.id },
      data: {
        totalPaidLifetime,
        totalHeld,
        cyclesCount: cycles.length,
        lastPaidAt,
      },
    });
    console.log(
      `  ✅ ${m.jobTitle}: paid=${totalPaidLifetime}, held=${totalHeld}, cycles=${cycles.length}`,
    );
  }

  console.log("\n🎉 Done!\n");
  console.log("═══ Test endpoints ═══");
  console.log(`  GET /api/retained-staff/dashboard`);
  console.log(`  GET /api/retained-staff`);
  console.log(`  GET /api/retained-staff/${m1.id}/cycles`);
  console.log(`  GET /api/admin/retained-staff`);
  console.log(`  GET /api/admin/retained-cycles\n`);
}

run()
  .catch((err) => {
    console.error("\n❌ Seed failed:", err.message);
    console.error(err.stack);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
